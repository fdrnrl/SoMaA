"""Нормализация ответов учеников (раздел 8.6)."""


def normalize_answer(answer: str) -> str:
    """Приводит ответ ученика к виду для сравнения с верным.

    Шаги строго по порядку:
    1. удалить все пробельные символы (пробелы, табуляции, переносы строк — и внутри строки тоже);
    2. заменить «.» на «,»;
    3. привести к нижнему регистру;
    4. заменить букву «е с двумя точками» (U+0451) на «е» (U+0435).

    Пустая строка остается пустой. Функция идемпотентна: повторный вызов ничего не меняет.
    Примеры: " 0.25" → "0,25"; "Пришел" → "пришел".
    """
    first_string = "".join(answer.split())
    second_string = first_string.replace(".", ",")
    third_string = second_string.lower()
    normalized = third_string.replace("ё", "е")
    return normalized
